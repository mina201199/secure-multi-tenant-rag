CREATE FUNCTION app_private.immutable_version() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (NEW.content,NEW.source_hash,NEW.tenant_id,NEW.document_id,NEW.created_at,NEW.id)
    IS DISTINCT FROM (OLD.content,OLD.source_hash,OLD.tenant_id,OLD.document_id,OLD.created_at,OLD.id)
 THEN RAISE EXCEPTION 'immutable version' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER immutable_version BEFORE UPDATE ON app_core.document_versions
FOR EACH ROW EXECUTE FUNCTION app_private.immutable_version();
