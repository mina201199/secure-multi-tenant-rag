CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA IF NOT EXISTS app_private;
REVOKE ALL ON SCHEMA app_private FROM PUBLIC;
CREATE TABLE app_private.runtime_secret (id boolean PRIMARY KEY DEFAULT true CHECK(id), value text NOT NULL);

CREATE TABLE app_core.document_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 10000) PRIMARY KEY,
    tenant_id bigint NOT NULL,
    document_id bigint NOT NULL,
    owner_id bigint NOT NULL,
    content text NOT NULL CHECK (octet_length(content) <= 1048576),
    source_hash text NOT NULL,
    visibility text NOT NULL DEFAULT 'private' CHECK (visibility IN ('private','company','selected')),
    state text NOT NULL DEFAULT 'processing' CHECK (state IN ('processing','ready','failed')),
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (tenant_id, id),
    UNIQUE (tenant_id, document_id, id),
    FOREIGN KEY (tenant_id, document_id) REFERENCES app_core.documents(tenant_id,id),
    FOREIGN KEY (tenant_id, owner_id) REFERENCES app_core.users(tenant_id,id)
);
INSERT INTO app_core.document_versions(id,tenant_id,document_id,owner_id,content,source_hash,visibility,state)
SELECT id,tenant_id,id,owner_id,content,encode(public.digest(content,'sha256'),'hex'),visibility,'ready'
FROM app_core.documents;
