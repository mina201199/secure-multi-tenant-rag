CREATE TABLE app_core.history_permissions (
    tenant_id bigint NOT NULL,
    version_id bigint NOT NULL,
    user_id bigint NOT NULL,
    granted_by bigint NOT NULL,
    PRIMARY KEY(tenant_id,version_id,user_id),
    FOREIGN KEY(tenant_id,version_id) REFERENCES app_core.document_versions(tenant_id,id),
    FOREIGN KEY(tenant_id,user_id) REFERENCES app_core.users(tenant_id,id),
    FOREIGN KEY(tenant_id,granted_by) REFERENCES app_core.users(tenant_id,id)
);
CREATE TABLE app_core.jobs (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    document_id bigint NOT NULL,
    version_id bigint NOT NULL UNIQUE,
    requested_by bigint NOT NULL,
    base_version_id bigint NOT NULL,
    status text NOT NULL DEFAULT 'queued' CHECK(status IN ('queued','running','done','failed','cancelled')),
    attempts integer NOT NULL DEFAULT 0 CHECK(attempts BETWEEN 0 AND 3),
    lease_hash text,
    lease_until timestamptz,
    error text,
    created_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY(tenant_id,document_id,version_id) REFERENCES app_core.document_versions(tenant_id,document_id,id),
    FOREIGN KEY(tenant_id,document_id,base_version_id) REFERENCES app_core.document_versions(tenant_id,document_id,id),
    FOREIGN KEY(tenant_id,requested_by) REFERENCES app_core.users(tenant_id,id)
);
CREATE TABLE app_core.transfer_requests (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL,
    applicant_id bigint NOT NULL,
    recipient_id bigint NOT NULL,
    supervisor_id bigint NOT NULL,
    reason text NOT NULL CHECK(length(reason) BETWEEN 1 AND 500),
    status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved','rejected')),
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL DEFAULT now()+interval '7 days',
    decided_at timestamptz,
    CHECK(applicant_id<>recipient_id AND supervisor_id<>recipient_id),
    UNIQUE(tenant_id,id),
    FOREIGN KEY(tenant_id,applicant_id) REFERENCES app_core.users(tenant_id,id),
    FOREIGN KEY(tenant_id,recipient_id) REFERENCES app_core.users(tenant_id,id),
    FOREIGN KEY(tenant_id,supervisor_id) REFERENCES app_core.users(tenant_id,id)
);
CREATE TABLE app_core.transfer_documents (
    tenant_id bigint NOT NULL,
    transfer_id bigint NOT NULL,
    document_id bigint NOT NULL,
    expected_revision bigint NOT NULL,
    expected_version_id bigint NOT NULL,
    PRIMARY KEY(tenant_id,transfer_id,document_id),
    FOREIGN KEY(tenant_id,transfer_id) REFERENCES app_core.transfer_requests(tenant_id,id),
    FOREIGN KEY(tenant_id,document_id,expected_version_id) REFERENCES app_core.document_versions(tenant_id,document_id,id)
);
CREATE TABLE app_core.transfer_versions (
    tenant_id bigint NOT NULL,
    transfer_id bigint NOT NULL,
    document_id bigint NOT NULL,
    version_id bigint NOT NULL,
    PRIMARY KEY(tenant_id,transfer_id,version_id),
    FOREIGN KEY(tenant_id,transfer_id,document_id) REFERENCES app_core.transfer_documents(tenant_id,transfer_id,document_id),
    FOREIGN KEY(tenant_id,document_id,version_id) REFERENCES app_core.document_versions(tenant_id,document_id,id)
);
CREATE TABLE app_core.audit_events (
    id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    tenant_id bigint NOT NULL REFERENCES app_core.tenants(id),
    actor_id bigint,
    action text NOT NULL,
    document_id bigint,
    version_id bigint,
    event_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY(tenant_id,actor_id) REFERENCES app_core.users(tenant_id,id),
    FOREIGN KEY(tenant_id,document_id) REFERENCES app_core.documents(tenant_id,id),
    FOREIGN KEY(tenant_id,version_id) REFERENCES app_core.document_versions(tenant_id,id)
);
